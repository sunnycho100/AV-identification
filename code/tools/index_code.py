"""Build a navigation index for every source file and all historical research scripts."""

import ast
import json
from collections import Counter
from pathlib import Path
from export_repository import ROOT, candidates


def group(name: str) -> str:
    if any(word in name for word in ("paper", "report", "summarize", "plot", "visualize")):
        return "Reporting and manuscript"
    if any(word in name for word in ("check", "validate", "verify", "Test-", "test_", "audit")):
        return "Validation and diagnostics"
    if any(
        word in name
        for word in (
            "classifier",
            "classify",
            "predict_field",
            "todd_experiment_train",
            "frozen_duration",
        )
    ):
        return "Classification and training"
    if any(word in name for word in ("review", "leader", "seed")):
        return "Human review and identity"
    if any(
        word in name
        for word in ("finetune", "adapt", "refine", "calibrat", "height", "scale", "registration")
    ):
        return "Detector and geometry adaptation"
    if any(
        word in name
        for word in ("bootstrap", "Import-", "Sync-", "restore", "workspace", "revision", "Catalog")
    ):
        return "Workspace and data administration"
    return "Trajectory extraction and evaluation"


def description(path: Path) -> str:
    if path.suffix == ".py":
        try:
            doc = ast.get_docstring(ast.parse(path.read_text(encoding="utf-8-sig")))
            if doc:
                return doc.splitlines()[0].replace("|", "/")[:130]
        except (SyntaxError, UnicodeError):
            pass
    return "Historical research entry; inspect its configuration before execution."


def main():
    sources = [
        p
        for p in candidates(ROOT)
        if p.suffix in {".py", ".ps1", ".sh", ".cpp", ".cu", ".h", ".js"}
    ]
    rows = [
        {
            "path": p.relative_to(ROOT).as_posix(),
            "bytes": p.stat().st_size,
            "group": group(p.name),
            "description": description(p),
        }
        for p in sorted(sources)
    ]
    destination = ROOT / "code/docs"
    (destination / "source_index.json").write_text(
        json.dumps(rows, ensure_ascii=False, indent=2) + "\n", encoding="utf-8"
    )
    historical = [r for r in rows if r["path"].startswith("code/scripts/")]
    lines = [
        "# Code navigation",
        "",
        "Generated by `python code/manage.py inventory`.",
        "",
        "Maintained reusable interfaces: `code/src/roadside_identification/`. Cross-platform commands: `code/manage.py`.",
        "Research scripts retain their recorded paths and configurations for reproducibility. They are not interchangeable generic commands; many require local historical artifacts. New reusable logic belongs in the package, with new protocols in configs and outputs in experiments.",
        "",
        "The complete file index is [source_index.json](source_index.json). Third-party AB3DMOT is intentionally not part of the publication tree.",
        "",
    ]
    for category in sorted({r["group"] for r in historical}):
        lines.extend(["## " + category, "", "| Historical entry | Purpose |", "|---|---|"])
        for row in historical:
            if row["group"] == category:
                relative = Path(row["path"]).relative_to("code")
                name = relative.relative_to("scripts").as_posix()
                lines.append(f"| [{name}](../{relative.as_posix()}) | {row['description']} |")
        lines.append("")
    (destination / "CODE_INDEX.md").write_text("\n".join(lines) + "\n", encoding="utf-8")
    print(
        json.dumps(
            {
                "indexed_sources": len(rows),
                "historical_entries": len(historical),
                "groups": dict(Counter(r["group"] for r in historical)),
            }
        )
    )


if __name__ == "__main__":
    main()
