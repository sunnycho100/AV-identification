"""Generate supplementary residual table from archived per-fit predictions/metrics."""
from pathlib import Path
import argparse
import hashlib,json
HERE = Path(__file__).resolve().parent
ROOT = HERE.parents[1]
parser = argparse.ArgumentParser(description=__doc__)
parser.add_argument('--evidence-root', type=Path, required=True,
                    help='Directory containing archived experiment evidence (not bundled).')
parser.add_argument('--output', type=Path, default=ROOT / 'outputs/publication',
                    help='Directory for generated figures, tables, and provenance.')
args = parser.parse_args()
import pandas as pd

EVIDENCE = args.evidence_root.resolve()
PAPER = args.output.resolve()
PAPER.mkdir(parents=True, exist_ok=True)
for folder in ('tables', 'figs'):
    (PAPER / folder).mkdir(exist_ok=True)
DATA=EVIDENCE/'residual/all_metrics.csv'
d=pd.read_csv(DATA);d=d[d['mode'].eq('expanded')]
METHODS=[('CTH-OE','CTH residual threshold'),('IDM-OE','IDM residual threshold'),('PI-Koopman-CTH','PI-CTH residual threshold'),('PI-Koopman-IDM','PI-IDM residual threshold'),('RF_native11','RF: trajectory features'),('RF_native11_ordinary4','RF + ordinary residuals (4)'),('RF_native11_PI4','RF + PI residuals (4)'),('RF_native11_physics8','RF + combined residuals (8)')]
records=[];lines=[]
for model,label in METHODS:
 cells=[]
 for role,fold in [('test',None),('test',2),('external_test',None)]:
  q=d[d.model.eq(model)&d.role.eq(role)]
  if fold is not None:q=q[q.fold.eq(fold)]
  by_seed=100*q.groupby('seed').accuracy.mean();mu=float(by_seed.mean());sd=float(by_seed.std(ddof=1)) if len(by_seed)>1 else None
  cell=f'${mu:.2f}\\pm{sd:.2f}$' if sd is not None else f'{mu:.2f}'
  cells.append(cell);records.append(dict(model=model,role=role,fold=fold,mean_percent=mu,seed_sd_percent=sd,n_seeds=len(by_seed),latex=cell))
 if model=='RF_native11':lines.append(r'\midrule')
 lines.append(label+' & '+' & '.join(cells)+r' \\')
text=r'''% Generated by revision_20261023_residual_aux/build_table.py from immutable run metrics.
\begin{table}[pos=tbp]
\caption{Supplementary single-segment accuracy (\%) with residual thresholds and RF feature augmentation.}
\label{tab:residual-auxiliary}
\centering
\small
\setlength{\tabcolsep}{5pt}
\begin{tabular}{lrrr}
\toprule
Method & Vicolungo & Highway source & Held-out CATS \\
\midrule
'''+ '\n'.join(lines)+r'''
\bottomrule
\end{tabular}
\par\smallskip\begin{minipage}{\linewidth}\footnotesize
All methods use expanded training and the original source splits. Vicolungo averages three test folds; the highway column reports part~4 alone. RF values are means $\pm$ one sample SD across five seeds, after averaging folds where applicable. Threshold results are deterministic fold means. CATS scores average the three source-fold configurations on the same 962 held-out windows; vehicles recur across recordings. Parenthetical feature counts denote added descriptors; every augmented RF retains all 440 original trajectory inputs. These are full-window results, not the matched repeated-observation cohort.
\end{minipage}
\end{table}
'''
out=PAPER/'tables/residual_auxiliary.tex';out.write_text(text)
(PAPER/'table_evidence.json').write_text(json.dumps(dict(source=str(DATA.relative_to(EVIDENCE)),source_sha256=hashlib.sha256(DATA.read_bytes()).hexdigest(),output=str(out.relative_to(PAPER)),output_sha256=hashlib.sha256(out.read_bytes()).hexdigest(),cells=records),indent=2)+'\n')
print(out)
